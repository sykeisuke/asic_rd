"""Write one bench of the cell_trannoise cell: VACASK (transient noise) or the
ngspice reference, both from the same stimulus and the same subcircuits.

    python3 ct_bench.py vacask  <out.sim>   <net.inc> [--seed N] [--scale S] [--fmax F]
                                [--reltol R] [--maxstep M] [PARAM=value ...]
    python3 ct_bench.py ngspice <out.spice> [PARAM=value ...]

PARAM=value overrides a tb_params.inc line (POS, NREC, TFIRST, NCNT).

The circuit (both engines):
  xr  ramp_simple_d (vramp rst vrlo ibr avdd 0)         IREF_RAMP sunk from its diode node ibr
  xc  atop_cell     (vin vramp s0 s1 s2 vref vref ibc q clk avdd 0 dvdd 0)
                    IREF_CMP sunk from the comparator's diode node ibc;
                    vref is both the S2 level and the comparator's inp (v5: one node)
  cq  CQ on q
Ideal sources: avdd = dvdd = VDD, vref = VDD/2, vrlo = VR_LO, vin = VIN, the
three switch controls, ramp_rst, the count clock. The ngspice bench .includes
the PDK models, the std-cell library and ../Analog_top/analog_top.spice
(every subcircuit read by path); the VACASK bench includes work/models.inc and
the translation ct_netlist.py made of the same subcircuits.

Noise (VACASK): every device of the groups left noisy in net.inc, noisefmin
1 kHz .. noisefmax, SDE mode, oversample 3. tran_noiselte 10, tran_extraoct 0,
gmin 1e-15 as ../cell_trannoise_bkp/cell_trannoise. reltol: 1e-6 for noisy runs (at VACASK's
default 1e-3 transient noise leaks charge onto the floating plate:
../cell_trannoise_bkp/cell_trannoise, +1 LSB at c240); the noiseless runs use the default with
maxstep 0.2 ns, as ../cell_trannoise_bkp/cell_trannoise's q runs.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ct_common import load_params, num  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
D = "/foss/designs/mixed_signal"
STDLIB = "/foss/pdk_libs/gf180mcuD/libs.ref/gf180mcu_as_sc_mcu7t3v3/spice/gf180mcu_as_sc_mcu7t3v3.spice"
MACRO = D + "/Analog_top/analog_top.spice"
MODELS = D + "/cell_trannoise/work/models.inc"


def sources(P):
    """(name, n+, n-, kind, values) of every ideal source; values in SPICE PULSE order."""
    T, E = P["TCOUNT"], P["TEDGE"]
    span = P["TRREL"] + P["NCNT"] * T
    ws2 = span + 10e-9 - E
    return [
        ("vavdd", "avdd", "0", "dc", P["VDD"]),
        ("vdvdd", "dvdd", "0", "dc", P["VDD"]),
        ("vvref", "vref", "0", "dc", P["VMID"]),
        ("vvrlo", "vrlo", "0", "dc", P["VR_LO"]),
        ("vvin", "vin", "0", "dc", P["VIN"]),
        ("iramp", "ibr", "0", "idc", P["IREF_RAMP"]),
        ("icmp", "ibc", "0", "idc", P["IREF_CMP"]),
        # S2 opens at t0 (the sample), S0 TNOV later; both close at TE + 10 ns
        ("vs2", "s2", "0", "pulse", (P["VDD"], 0, P["TFIRST"], E, E, ws2, P["PCONV"])),
        ("vs0", "s0", "0", "pulse", (P["VDD"], 0, P["TFIRST"] + P["TNOV"], E, E, ws2 - P["TNOV"], P["PCONV"])),
        # S1 closes at t0 + 2 TNOV, opens at TE
        ("vs1", "s1", "0", "pulse", (0, P["VDD"], P["TFIRST"] + 2 * P["TNOV"], E, E, span - 2 * P["TNOV"] - E, P["PCONV"])),
        # ramp_rst falls at TR (a rising clock edge), rises at TE + 5 ns
        ("vrst", "rst", "0", "pulse", (P["VDD"], 0, P["TFIRST"] + P["TRREL"], E, E, P["NCNT"] * T + 5e-9 - E, P["PCONV"])),
        # count clock: rises at TCLK0 + j TCOUNT (so at every t0 and TR), falls TCOUNT/2 later
        ("vclk", "clk", "0", "pulse", (0, P["VDD"], P["TCLK0"], E, E, T / 2 - E, T)),
    ]


def vacask(P, net, seed, scale, fmax, reltol, maxstep):
    lines = ["cell_trannoise: one Analog_top cell on ramp_simple_d, VACASK transient noise", "",
             "// GENERATED by cell_trannoise/ct_bench.py; POS %.6g NREC %d TFIRST %.6g" % (P["POS"], P["NREC"], P["TFIRST"]),
             "ground 0", 'include "%s"' % MODELS, 'include "%s"' % net,
             'load "resistor.osdi"', 'load "capacitor.osdi"', "model resistor resistor",
             "model capacitor capacitor", "model vsource vsource", "model isource isource", ""]
    for name, a, b, kind, v in sources(P):
        if kind == "dc":
            lines.append("%s (%s %s) vsource dc=%.9g" % (name, a, b, v))
        elif kind == "idc":
            lines.append("%s (%s %s) isource dc=%.9g" % (name, a, b, v))
        else:
            lines.append('%s (%s %s) vsource type="pulse" val0=%.9g val1=%.9g delay=%.12g rise=%.6g fall=%.6g '
                         "width=%.12g period=%.12g" % ((name, a, b) + tuple(v)))
    lines += ["xr (vramp rst vrlo ibr avdd 0) ramp_simple_d",
              "xc (vin vramp s0 s1 s2 vref vref ibc q clk avdd 0 dvdd 0) atop_cell",
              "cq (q 0) capacitor c=%.6g" % P["CQ"], "",
              "control", "  var mm=0",
              "  options temp=27 tnom=27 gmin=1e-15 tran_extraoct=0 tran_noiselte=10%s"
              % (" reltol=%g" % reltol if reltol > 0 else ""),
              '  save v(q) v(clk) v(vramp) v("xc:dout") v("xc:bot")',
              '  analysis tn tran stop=%.9g step=1n noisemode="sde" noisefmax=%g noisefmin=1e3 oversample=3 '
              "noiseseed=%d noisescale=%g%s" % (P["TSTOP"], fmax, seed, scale, " maxstep=%g" % maxstep if maxstep > 0 else ""),
              "endc", ""]
    return "\n".join(lines)


def ngspice(P):
    lines = ["* cell_trannoise: ngspice reference (noiseless) of the same cell bench",
             "* GENERATED by cell_trannoise/ct_bench.py; POS %.6g NREC %d" % (P["POS"], P["NREC"]),
             ".include /foss/pdks/gf180mcuD/libs.tech/ngspice/design.ngspice",
             ".lib /foss/pdks/gf180mcuD/libs.tech/ngspice/sm141064.ngspice typical",
             ".lib /foss/pdks/gf180mcuD/libs.tech/ngspice/sm141064.ngspice mimcap_typical",
             ".include " + STDLIB, ".include " + MACRO,
             ".temp 27", ".options rshunt=1e15 gmin=1e-15"]
    for name, a, b, kind, v in sources(P):
        if kind == "dc":
            lines.append("%s %s %s dc %.9g" % (name.upper(), a, b, v))
        elif kind == "idc":
            lines.append("%s %s %s dc %.9g" % (name.upper(), a, b, v))
        else:
            lines.append("%s %s %s PULSE(%s)" % ((name.upper(), a, b, " ".join("%.12g" % x for x in v))))
    lines += ["XR vramp rst vrlo ibr avdd 0 ramp_simple_d",
              "XC vin vramp s0 s1 s2 vref vref ibc q clk avdd 0 dvdd 0 atop_cell",
              "CQ q 0 %.6g" % P["CQ"],
              ".control", "set filetype=binary",
              "tran 0.1n %.9g" % P["TSTOP"],
              "write tb.raw v(q) v(clk) v(vramp) v(xc.dout) v(xc.bot)",
              "quit", ".endc", ".end", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("engine", choices=("vacask", "ngspice"))
    ap.add_argument("out")
    ap.add_argument("net", nargs="?")
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--scale", type=float, default=1.0)
    ap.add_argument("--fmax", type=float, default=2e9)
    ap.add_argument("--reltol", type=float, default=0.0)
    ap.add_argument("--maxstep", type=float, default=0.0)
    ap.add_argument("params", nargs="*")
    a = ap.parse_intermixed_args()
    ov = {}
    params = list(a.params)
    if a.engine == "vacask" and a.net and "=" in a.net:
        sys.exit("FAIL: ct_bench.py vacask needs <net.inc>")
    if a.engine == "ngspice" and a.net:
        params.insert(0, a.net)
    for x in params:
        k, v = x.split("=", 1)
        ov[k] = num(v)
    P = load_params(ov)
    text = vacask(P, a.net, a.seed, a.scale, a.fmax, a.reltol, a.maxstep) if a.engine == "vacask" else ngspice(P)
    open(a.out, "w").write(text)


if __name__ == "__main__":
    main()
