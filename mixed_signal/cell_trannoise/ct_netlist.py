"""Translate ONE cell of the Analog_top macro and its ramp into VACASK
subcircuits, one noise group per block, so a run can leave any set of blocks
noisy.

    python3 ct_netlist.py [quiet groups ...] > net.inc     (container, from this block)

Adapted from ../Analog_top_bkp/Analog_top_v4/trannoise/at_netlist.py (same device mapping,
quiet-copy mechanism and NF1 finger expansion). The subcircuits are read BY
PATH, never copied:

  ramp_simple_d, atop_cell, sw_s0/1/2, comparator_d, latch
                          ../Analog_top/analog_top.spice (GENERATED by its
                          schematic.sh from the drawings)
  the latch's std cell    /foss/pdk_libs/.../gf180mcu_as_sc_mcu7t3v3.spice
                          (gf180mcu_as_sc_mcu7t3v3__dfxtn_2; make pdk-libs)

Device mapping:
  MOS  -> the converted BSIM4 wrapper (nfet_03v3 / pfet_03v3), or its quiet copy
          (_q: ntnoi = noia = noib = noic = 0) when its group is quiet. Instance
          parameters l w nf m ad as pd ps nrd nrs sa sb sd pass through;
          comparator_d's PDK S/D templates ('int((nf+1)/2) * W/nf * 0.18u') are
          evaluated per instance. NF1: a NOISY device with nf > 1 becomes nf
          single-finger devices binned on the total W (nfs = nf): VACASK's bsim4
          drain flicker grows with nf and ngspice's does not.
  MIM  -> C = 1.99e-3 W L + 2.383e-10 x 2 (W + L) plus the PDK's r_leak, noiseless.
  Std-cell node names carry '#' (a_1709_68#): written as 'h'.
Bench aid added here: atop_cell rlkb (bot vss), rlkt (top vss), 1e15 ohm,
noisy=0 -- the DC path the ngspice bench gets from `.options rshunt=1e15`.

Noise groups:
  ramp   ramp_simple_d (XPS, XCR, XRST and its pbias diode XRD)
  cmp    comparator_d (incl. its pbias diode XREFP)
  ff     latch = gf180mcu_as_sc_mcu7t3v3__dfxtn_2 (26 MOS)
  sw     S0 / S1 / S2 and the cell's three control inverters
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MS = os.path.dirname(HERE)
SI = {"f": 1e-15, "p": 1e-12, "n": 1e-9, "u": 1e-6, "m": 1e-3, "k": 1e3, "meg": 1e6, "g": 1e9, "t": 1e12}
MOS = {"nfet_03v3", "pfet_03v3"}
MIM = "cap_mim_2f0_m4m5_noshield"
GLEAK = 9.51e-10 / 5 * 10000
GROUPS = ("ramp", "cmp", "ff", "sw")
STDCELL = "gf180mcu_as_sc_mcu7t3v3__dfxtn_2"
STDLIB = "/foss/pdk_libs/gf180mcuD/libs.ref/gf180mcu_as_sc_mcu7t3v3/spice/gf180mcu_as_sc_mcu7t3v3.spice"
MACRO = os.path.join(MS, "Analog_top", "analog_top.spice")
NF1 = os.environ.get("CT_NF1", "1") == "1"
SOURCES = (
    (MACRO, {"ramp_simple_d", "atop_cell", "sw_s0", "sw_s1", "sw_s2", "comparator_d", "latch"}),
    (STDLIB, {STDCELL}),
)
ORDER = ("ramp_simple_d", "sw_s0", "sw_s1", "sw_s2", "comparator_d", STDCELL, "latch", "atop_cell")
GROUP_OF = {"ramp_simple_d": "ramp", "comparator_d": "cmp", STDCELL: "ff", "latch": "ff",
            "sw_s0": "sw", "sw_s1": "sw", "sw_s2": "sw"}
KV = re.compile(r"(\w+)\s*=\s*('[^']*'|\{[^}]*\}|\"[^\"]*\"|\S+)")
KNOWN = ("ad", "as", "pd", "ps", "nrd", "nrs", "sa", "sb", "sd")


def num(tok):
    m = re.match(r"^([-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?)(meg|[fpnumkgt])?$", tok, re.I)
    if not m:
        return None
    return float(m.group(1)) * SI.get((m.group(2) or "").lower(), 1.0)


def node(n):
    return n.lower().replace("#", "h")


def ev(s, local=None):
    s = s.strip().strip("{}'\"")
    v = num(s)
    if v is not None:
        return v
    expr = re.sub(r"(?<![\w.])((?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?)(meg|[fpnumkgt])(?![\w])",
                  lambda m: repr(float(m.group(1)) * SI[m.group(2).lower()]), s, flags=re.I)
    local = local or {}

    def name(m):
        k = m.group(0).lower()
        if k == "int":
            return "int"
        if k not in local:
            raise SystemExit("FAIL: ct_netlist: unknown name %r in %r" % (m.group(0), s))
        return repr(local[k])
    expr = re.sub(r"\b[A-Za-z_]\w*\b", name, expr)
    return float(eval(expr, {"__builtins__": {}, "int": int}))


def read(path, names, subckts):
    cur = None
    lines = []
    for raw in open(path):
        line = raw.rstrip("\n").rstrip("\r")
        if line.startswith("+") and lines:
            lines[-1] += " " + line[1:]
        else:
            lines.append(line)
    for line in lines:
        s = line.split(";")[0].strip()
        if not s or s.startswith("*"):
            continue
        low = s.lower()
        if low.startswith(".subckt"):
            p = s.split()
            cur = p[1].lower() if p[1].lower() in names else None
            if cur:
                subckts[cur] = {"ports": [node(x) for x in p[2:] if "=" not in x], "dev": []}
            continue
        if low.startswith(".ends"):
            cur = None
            continue
        if cur is None:
            continue
        if s.startswith("."):
            raise SystemExit("FAIL: ct_netlist: dot card inside .subckt %s: %r" % (cur, s))
        subckts[cur]["dev"].append(s)
    miss = names - set(subckts)
    if miss:
        raise SystemExit("FAIL: ct_netlist: %s not found in %s" % (sorted(miss), path))


def parse_dev(s):
    kvs = KV.findall(s)
    head = KV.sub("", s).split()
    name = head[0].lower()
    if name[0] != "x":
        raise SystemExit("FAIL: ct_netlist: unsupported device line %r" % s)
    master = head[-1].lower()
    nodes = [node(x) for x in head[1:-1]]
    raw = {k.lower(): v for k, v in kvs}
    local = {}
    for k in ("w", "l", "nf", "m"):
        if k in raw:
            local[k] = ev(raw[k])
    local.setdefault("nf", 1.0)
    local.setdefault("m", 1.0)
    return name, master, nodes, {k: ev(v, local) for k, v in raw.items()}


def group(sc, inst):
    if sc in GROUP_OF:
        return GROUP_OF[sc]
    if sc == "atop_cell":
        return "sw" if inst.startswith("xi") else "none"   # control inverters; the MIM; sub-instances
    raise SystemExit("FAIL: ct_netlist: no noise group for %s.%s" % (sc, inst))


def emit(subckts, quiet):
    bad = set(quiet) - set(GROUPS)
    if bad:
        raise SystemExit("FAIL: ct_netlist: unknown noise groups %s" % sorted(bad))
    out = ["// GENERATED by cell_trannoise/ct_netlist.py from ../Analog_top/analog_top.spice "
           "and the dfxtn_2 std cell; quiet groups: %s; NF1 %d" % (",".join(sorted(quiet)) or "none", NF1)]
    counts, nf1 = {}, 0
    for sc in ORDER:
        d = subckts[sc]
        out.append("subckt %s (%s)" % (sc, " ".join(d["ports"])))
        for s in d["dev"]:
            name, master, nodes, p = parse_dev(s)
            g = group(sc, name)
            q = g in quiet or g == "none"
            if master in MOS:
                counts[g] = counts.get(g, 0) + 1
                if len(nodes) != 4:
                    raise SystemExit("FAIL: ct_netlist: %s.%s has %d terminals" % (sc, name, len(nodes)))
                unknown = set(p) - {"l", "w", "nf", "m"} - set(KNOWN)
                if unknown:
                    raise SystemExit("FAIL: ct_netlist: %s.%s unknown MOS parameters %s" % (sc, name, unknown))
                if p["w"] > 100.001e-6:
                    raise SystemExit("FAIL: ct_netlist: %s.%s W=%.4g above the 100 um bin ceiling" % (sc, name, p["w"]))
                nf = int(round(p.get("nf", 1)))
                m = int(round(p.get("m", 1)))
                if not q and nf > 1 and NF1:
                    nf1 += 1
                    sc_ = {"ad": 1.0 / nf, "as": 1.0 / nf, "pd": 1.0 / nf, "ps": 1.0 / nf, "nrd": nf, "nrs": nf,
                           "sa": 1.0, "sb": 1.0, "sd": 1.0}
                    extra = " ".join("%s=%.6g" % (k, p[k] * sc_[k]) for k in KNOWN if k in p)
                    out.append("  %s (%s) %s w=%.6g l=%.6g nf=1 m=%d nfs=%d %s" % (
                        name, " ".join(nodes), master, p["w"] / nf, p["l"], m, nf, extra))
                    continue
                extra = " ".join("%s=%.6g" % (k, p[k]) for k in KNOWN if k in p)
                out.append("  %s (%s) %s%s w=%.6g l=%.6g nf=%d m=%d %s" % (
                    name, " ".join(nodes), master, "_q" if q else "", p["w"], p["l"], nf, m, extra))
            elif master == MIM:
                w, l = p["c_width"], p["c_length"]
                c = 1.99e-3 * w * l + 2.383e-10 * 2 * (w + l)
                out.append("  %s (%s %s) capacitor c=%.6g" % (name, nodes[0], nodes[1], c))
                out.append("  %s_leak (%s %s) resistor r=%.6g noisy=0" % (name, nodes[0], nodes[1], 1.0 / (GLEAK * w * l)))
            elif master in subckts:
                if p:
                    raise SystemExit("FAIL: ct_netlist: parameters on subcircuit instance %s.%s" % (sc, name))
                out.append("  %s (%s) %s" % (name, " ".join(nodes), master))
            else:
                raise SystemExit("FAIL: ct_netlist: %s.%s: unknown master %r" % (sc, name, master))
        if sc == "atop_cell":
            out.append("  rlkb (bot vss) resistor r=1e15 noisy=0     // bench aid: DC path of the floating plate")
            out.append("  rlkt (top vss) resistor r=1e15 noisy=0     // bench aid")
        out.append("ends\n")
    return "\n".join(out) + "\n", counts, nf1


def main():
    subckts = {}
    for f, names in SOURCES:
        read(f, names, subckts)
    text, counts, nf1 = emit(subckts, set(sys.argv[1:]))
    sys.stdout.write(text)
    for g, n in sorted(counts.items()):
        sys.stderr.write("ct_netlist_mos_%s = %d\n" % (g, n))
    sys.stderr.write("ct_netlist_nf1_devices = %d\n" % nf1)


if __name__ == "__main__":
    main()
