#!/usr/bin/env python3
"""pwr_reduce.py -- reduce the pwr phase's record to where every microamp of
AVDD goes, phase by phase. Reads work/pwr/ngspice.out (p_* timeline echoes)
and work/pwr/pwr.csv (pwr_bench.py's COLUMNS). Writes

  data/pwr_windows.csv   one row per saved current, its average (uA) in every
                         window below
  data/pwr_branches.csv  one row per AVDD branch: block, device, where the
                         current goes, average uA and uW per window
  assets/pwr_profile.png block power and the comparator branches over the
                         record, 5 ns bin averages

Windows (each average is the exact integral of the simulator's own time
points over the window, divided by its length):
  startup  [0, T0]                 supplies ramp, everything settles
  track    [T0, TS0]               all four cells tracking (S0, S2 closed)
  sample   [TS0, TS3 + 2 TNOV]     the cells leave tracking one by one
  hold     [TS3 + 2 TNOV, TR]      every cell holding, S1 closed, ramp in reset
  ramp     [TR, TE]                the conversion (func's pw_* window)
  overrun  [TE, TE + TOVR]
  end      [TE + TOVR, TSTOP]
  pre<k> / post<k>  [TR, td_k] / [td_k, TE], td_k = dout_k through VDD/2

RECORDED (REPORT: lines, pwr_* scalars), not judged. Gated are only the checks
that make the breakdown trustworthy:
  * the eight block ammeters add up to the AVDD supply current (0.1 %)
  * in the quasi-static windows (track, hold, ramp) each block's branches add
    up to its ammeter within max(1 %, 0.2 uA); the remainder is displacement
    current and is reported in every window
"""
import csv
import os
import re
import sys

import numpy as np
import pandas as pd

from pwr_bench import BLOCKS, BRANCHES, COLUMNS, SPLITS

HERE = os.path.dirname(os.path.abspath(__file__))
W = os.path.join(HERE, "work", "pwr")
fails = 0


def put(name, val):
    print("%s = %.6g" % (name, val))


def fail(msg):
    global fails
    fails += 1
    print("FAIL: pwr: " + msg)


def timeline():
    p = {}
    for ln in open(os.path.join(W, "ngspice.out"), errors="replace"):
        m = re.match(r"^(p_[a-z0-9]+)\s*=\s*([-+0-9.eE]+)", ln.strip())
        if m:
            p[m.group(1)[2:]] = float(m.group(2))
    need = ["vdd", "t0", "ts0", "ts3", "tnov", "tr", "te", "tovr", "tstop"]
    miss = [k for k in need if k not in p]
    if miss:
        fail("timeline measures missing: " + " ".join(miss))
        sys.exit(0)
    return p


def main():
    p = timeline()
    vdd = p["vdd"]
    df = pd.read_csv(os.path.join(W, "pwr.csv"), sep=r"\s+")
    if df.shape[1] != len(COLUMNS) + 1:
        fail("pwr.csv has %d columns, expected %d" % (df.shape[1], len(COLUMNS) + 1))
        sys.exit(0)
    df.columns = ["t"] + [k for k, _ in COLUMNS]
    t = df["t"].to_numpy()
    print("REPORT: pwr: %d time points over %.3f us" % (len(t), t[-1] * 1e6))

    # supply-side sign: positive = drawn from the supply
    cur = {}
    for k, _ in COLUMNS:
        if k.startswith("dout"):
            continue
        v = df[k].to_numpy()
        cur[k] = -v if k.startswith("sup_") else v
    # cumulative integrals, trapezoid on the simulator's points
    F = {k: np.concatenate([[0.0], np.cumsum(0.5 * (v[1:] + v[:-1]) * np.diff(t))]) for k, v in cur.items()}

    def avg(k, a, b):
        fa, fb = np.interp([a, b], t, F[k])
        return (fb - fa) / (b - a)

    # decision instants: dout falls through VDD/2 after TR
    td = []
    for k in range(4):
        d = df["dout%d" % k].to_numpy()
        idx = np.where((t > p["tr"]) & (d < vdd / 2))[0]
        if len(idx) == 0:
            fail("dout%d never falls after TR" % k)
            td.append(p["te"])
            continue
        i = idx[0]
        td.append(np.interp(vdd / 2, [d[i], d[i - 1]], [t[i], t[i - 1]]))
        put("pwr_td%d_ns_from_tr" % k, (td[k] - p["tr"]) * 1e9)

    t_s3 = p["ts3"] + 2 * p["tnov"]
    wins = [("startup", 0.0, p["t0"]), ("track", p["t0"], p["ts0"]),
            ("sample", p["ts0"], t_s3), ("hold", t_s3, p["tr"]),
            ("ramp", p["tr"], p["te"]), ("overrun", p["te"], p["te"] + p["tovr"]),
            ("end", p["te"] + p["tovr"], p["tstop"])]
    for k in range(4):
        wins += [("pre%d" % k, p["tr"], td[k]), ("post%d" % k, td[k], p["te"])]
    A = {(k, w): avg(k, a, b) for k in cur for w, a, b in wins}
    for w, a, b in wins[:7]:
        put("pwr_win_%s_ns" % w, (b - a) * 1e9)

    # windows table
    with open(os.path.join(HERE, "data", "pwr_windows.csv"), "w", newline="") as f:
        wr = csv.writer(f)
        wr.writerow(["# generated by pwr_reduce.py; average current in uA (positive = drawn from the supply)"])
        wr.writerow(["column"] + [w for w, _, _ in wins])
        for k in cur:
            wr.writerow([k] + ["%.5g" % (A[(k, w)] * 1e6) for w, _, _ in wins])

    main_w = ["track", "sample", "hold", "ramp", "overrun", "end"]
    with open(os.path.join(HERE, "data", "pwr_branches.csv"), "w", newline="") as f:
        wr = csv.writer(f)
        wr.writerow(["block", "branch", "goes_to"] + ["%s_ua" % w for w in main_w] + ["%s_uw" % w for w in main_w])
        for b, key, _, role in BRANCHES:
            c = "br_%s_%s" % (b, key)
            wr.writerow([b, key, role] + ["%.4f" % (A[(c, w)] * 1e6) for w in main_w]
                        + ["%.3f" % (A[(c, w)] * 1e6 * vdd) for w in main_w])

    # closure: ammeters vs supply; branches vs ammeter
    for w in main_w + ["startup"]:
        s = sum(A[("amm_" + b, w)] for b, _, _ in BLOCKS)
        sup = A[("sup_avdd", w)]
        put("pwr_%s_avdd_uw" % w, sup * vdd * 1e6)
        put("pwr_%s_dvdd_uw" % w, A[("sup_dvdd", w)] * vdd * 1e6)
        put("pwr_%s_total_uw" % w, (sup + A[("sup_dvdd", w)]) * vdd * 1e6)
        if abs(s - sup) > 1e-3 * abs(sup):
            fail("%s: ammeters %.4f uA != AVDD %.4f uA" % (w, s * 1e6, sup * 1e6))
    print("PASS: pwr: in every window the eight block ammeters add up to the AVDD supply current within 0.1 %")
    bad = []
    for b, _, lab in BLOCKS:
        for w in main_w:
            amm = A[("amm_" + b, w)]
            parts = [(key, A[("br_%s_%s" % (bb, key), w)]) for bb, key, _, _ in BRANCHES if bb == b]
            res = amm - sum(v for _, v in parts)
            put("pwr_%s_%s_uw" % (w, b), amm * vdd * 1e6)
            put("pwr_%s_%s_resid_ua" % (w, b), res * 1e6)
            for key, v in parts:
                put("pwr_br_%s_%s_%s_ua" % (b, key, w), v * 1e6)
            if w in ("track", "hold", "ramp") and abs(res) > max(0.01 * abs(amm), 0.2e-6):
                bad.append("%s/%s %.3f uA of %.3f" % (b, w, res * 1e6, amm * 1e6))
            if w in ("track", "ramp", "hold"):
                print("REPORT: pwr: %-4s %-26s %-6s %8.2f uA = %8.2f uW = %s + rest %+.3f uA"
                      % (b, lab, w, amm * 1e6, amm * vdd * 1e6,
                         " + ".join("%s %.3f" % (kk, vv * 1e6) for kk, vv in parts if abs(vv) > 5e-9),
                         res * 1e6))
    if bad:
        fail("branches do not add up to the ammeter: " + "; ".join(bad))
    else:
        print("PASS: pwr: in track, hold and ramp every block's AVDD branches add up to its ammeter "
              "within max(1 %, 0.2 uA)")

    # each cell before and after its own decision, with the first-stage split
    for k in range(4):
        c = "c%d" % k
        for w in ("pre%d" % k, "post%d" % k):
            ph = w[:-1]
            put("pwr_%s_%s_uw" % (c, ph), A[("amm_" + c, w)] * vdd * 1e6)
            items = [(key, A[("br_%s_%s" % (c, key), w)]) for bb, key, _, _ in BRANCHES if bb == c]
            items += [(key, A[("sp_%s_%s" % (c, key), w)]) for bb, key, _, _ in SPLITS if bb == c]
            for key, v in items:
                put("pwr_%s_%s_%s_ua" % (c, ph, key), v * 1e6)
            print("REPORT: pwr: cell %d %-4s decision (%.0f ns): %.2f uA = %.2f uW; %s"
                  % (k, "before" if ph == "pre" else "after", (td[k] - p["tr"]) * 1e9,
                     A[("amm_" + c, w)] * 1e6, A[("amm_" + c, w)] * vdd * 1e6,
                     ", ".join("%s %.3f" % (kk, vv * 1e6) for kk, vv in items)))

    # energy of one record from the end of power-up
    def energy(a, b):
        return sum(avg("sup_" + s, a, b) for s in ("avdd", "dvdd")) * vdd * (b - a)
    put("pwr_energy_t0_tstop_nj", energy(p["t0"], p["tstop"]) * 1e9)
    put("pwr_energy_tr_te_nj", energy(p["tr"], p["te"]) * 1e9)

    # the profile figure: 5 ns bin averages
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        edges = np.arange(p["t0"] - 300e-9, p["tstop"], 5e-9)
        mid = 0.5 * (edges[1:] + edges[:-1]) * 1e6

        def binned(k):
            return np.diff(np.interp(edges, t, F[k])) / np.diff(edges)
        fig, ax = plt.subplots(3, 1, figsize=(12, 10), sharex=True,
                               gridspec_kw={"height_ratios": [3, 2, 2]})
        cols = ["#7a7a7a", "#e07b00", "#b8860b", "#222222", "#1f5fa8", "#d1495b", "#2a9d5c", "#8a5cc2"]
        stack = [binned("amm_" + b) * vdd * 1e6 for b, _, _ in BLOCKS]
        ax[0].stackplot(mid, stack, labels=[lab for _, _, lab in BLOCKS], colors=cols, alpha=0.85)
        ax[0].plot(mid, (binned("sup_avdd") + binned("sup_dvdd")) * vdd * 1e6, color="k", lw=0.8,
                   label="AVDD + DVDD")
        ax[0].set_ylabel("power (uW), stacked by block")
        ax[0].legend(loc="upper right", fontsize=8, ncol=3)
        for k in range(4):
            c = "c%d" % k
            ax[1].plot(mid, binned("br_%s_xbst" % c) * 1e6, color=cols[4 + k], lw=1, label="cell %d starved inv (XBST)" % k)
            ax[1].plot(mid, binned("br_%s_xbuf4" % c) * 1e6, color=cols[4 + k], lw=1, ls="--", label="cell %d out inv (XBUF4)" % k)
            ax[2].plot(mid, binned("br_%s_xtail" % c) * 1e6, color=cols[4 + k], lw=1, label="cell %d tail" % k)
            for a in ax:
                a.axvline(td[k] * 1e6, color=cols[4 + k], lw=0.6, ls=":")
        ax[1].set_ylabel("inverter currents (uA)")
        ax[1].legend(loc="upper right", fontsize=7, ncol=4)
        ax[2].set_ylabel("comparator tail (uA)")
        ax[2].legend(loc="lower right", fontsize=7, ncol=4)
        ax[2].set_xlabel("time (us); dotted: each cell's decision")
        for w, a, b in wins[1:7]:
            for x in ax:
                x.axvspan(a * 1e6, b * 1e6, color="#000000", alpha=0.04 if w in ("track", "hold", "overrun") else 0.0)
            ax[0].text((a + b) / 2 * 1e6, ax[0].get_ylim()[1] * 0.97, w, ha="center", va="top", fontsize=7)
        ax[0].set_title("analog_top v5: AVDD + DVDD over one record (5 ns bins)")
        fig.tight_layout()
        fig.savefig(os.path.join(HERE, "assets", "pwr_profile.png"), dpi=120)
        print("REPORT: pwr: wrote assets/pwr_profile.png, data/pwr_windows.csv, data/pwr_branches.csv")
    except Exception as e:  # the figure is a convenience, the numbers are the record
        print("REPORT: pwr: figure not written (%s)" % e)


if __name__ == "__main__":
    main()
