#!/usr/bin/env python3
"""op_bench.py -- write the op phase's bench: work/op/tb_op.spice is
tb_analog_top.spice (the same circuit, sources, rshunt aid and models) with its
tb_measure.inc replaced by work/op/tb_op.inc, which holds

  * the same .options as tb_measure.inc (reltol 1e-4, gmin 1e-15) and a
    transient to TR + 500 ns (both op instants lie before it)
  * one .measure per MOS x state x BSIM4 parameter (op_devices.MOS, PARAMS):
        op_<key>_<state>_<param> FIND @m.xdut.<path>.m0[<param>] AT=<instant>
  * per resistor and state: the two terminal voltages and the current through
    its head resistor rt1 (R = V / I in op_reduce.py)
  * in .control after the run: every MIM's capacitance read back from the
    model (@c.xdut.<path>.c_cap[capacitance]), echoed as op_cap_<key> = value

    python3 op_bench.py        (cwd = this block; op.sh calls it)
"""
import os

from op_devices import KCL_EXTRA, MIM, MOS, PARAMS, RES, STATES

HERE = os.path.dirname(os.path.abspath(__file__))
W = os.path.join(HERE, "work", "op")
BLOCK_ABS = "/foss/designs/mixed_signal/Analog_top"


def main():
    os.makedirs(W, exist_ok=True)
    deck = open(os.path.join(HERE, "tb_analog_top.spice")).read().splitlines()
    out, n = [], 0
    for ln in deck:
        if ln.strip().lower().startswith(".include") and ln.strip().endswith("tb_measure.inc"):
            out.append(".include %s/work/op/tb_op.inc" % BLOCK_ABS)
            n += 1
        else:
            out.append(ln)
    assert n == 1, "tb_analog_top.spice must include tb_measure.inc exactly once"
    out[0] = "* tb_op -- GENERATED by op_bench.py from tb_analog_top.spice (op phase); " + out[0].lstrip("* ")
    open(os.path.join(W, "tb_op.spice"), "w", newline="\n").write("\n".join(out) + "\n")

    L = ["* tb_op.inc -- GENERATED by op_bench.py (op_devices.py). The in-macro operating point.",
         ".options reltol=1e-4 gmin=1e-15",
         ".tran 0.1n {TR+500n} 0 2n"]
    for st, (t, _) in STATES.items():
        L.append(".param T_OP_%s='%s'" % (st.upper(), t))
    save = []
    for key, path, *_ in MOS:
        for p in PARAMS:
            save.append("@m.xdut.%s.m0[%s]" % (path, p))
    for _, v in KCL_EXTRA:
        save.append("@m.xdut." + v)
    for key, path, a, b, _ in RES:
        save.append("@r.xdut.%s.rt1[i]" % path)
        for nd in (a, b):
            if nd != "0":
                save.append("v(%s)" % nd)
    save = list(dict.fromkeys(save))
    for i in range(0, len(save), 6):
        L.append((".save " if i == 0 else "+ ") + " ".join(save[i:i + 6]))
    nmeas = 0
    for st in STATES:
        T = "{T_OP_%s}" % st.upper()
        for key, path, *_ in MOS:
            for p in PARAMS:
                L.append(".measure tran op_%s_%s_%s FIND @m.xdut.%s.m0[%s] AT=%s" % (key, st, p, path, p, T))
                nmeas += 1
        for k, v in KCL_EXTRA:
            L.append(".measure tran op_kcl_%s_%s FIND @m.xdut.%s AT=%s" % (k, st, v, T))
            nmeas += 1
        for key, path, a, b, _ in RES:
            L.append(".measure tran op_%s_%s_i FIND @r.xdut.%s.rt1[i] AT=%s" % (key, st, path, T))
            for tag, nd in (("va", a), ("vb", b)):
                if nd == "0":
                    L.append(".measure tran op_%s_%s_%s PARAM='0'" % (key, st, tag))
                else:
                    L.append(".measure tran op_%s_%s_%s FIND v(%s) AT=%s" % (key, st, tag, nd, T))
            nmeas += 3
    L += [".control", "set num_threads=1", "run"]
    for key, path, *_ in MIM:
        L.append("let cc = @c.xdut.%s.c_cap[capacitance]" % path)
        L.append('echo "op_cap_%s = $&cc"' % key)
    L += ["quit", ".endc"]
    open(os.path.join(W, "tb_op.inc"), "w", newline="\n").write("\n".join(L) + "\n")
    print("REPORT: op: wrote work/op/tb_op.spice + tb_op.inc: %d MOS x %d states x %d parameters, %d resistors, "
          "%d MIM readbacks (%d measures)" % (len(MOS), len(STATES), len(PARAMS), len(RES), len(MIM), nmeas))


if __name__ == "__main__":
    main()
