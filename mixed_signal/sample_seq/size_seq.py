"""Write sample_seq.spice, the sampling sequencer, for N delay cells per stage.

    python3 size_seq.py write N      the deck for N cells per stage (no simulation)
    python3 size_seq.py              re-write the deck from data/sizing.json

The size phase (bench.py size) fits each PVT cell's three gaps to a + b N and
records the smallest even N (>= N_MIN) for which every gap is >= GAP_MARGIN x
the four-inverter delay of that cell; it then calls write(). Nothing else
writes the deck; never hand-edit it.
"""
import json
import os
import sys

from seq_common import BLOCK, LIB, NCELLS, DLY_CELL

P = LIB + "__"


def g(name, cell, *pins):
    """a library cell line; pins in the library's own subcircuit order after the supplies"""
    return "%s vdd vdd vss vss %s %s%s" % (name, " ".join(pins), P, cell)


def deck(n):
    if n < 2 or n % 2:
        raise SystemExit("FAIL: size_seq: N = %d delay inverters per stage must be even and >= 2" % n)
    L = []
    a = L.append
    a("* sample_seq -- the on-chip sampling sequencer of the four bottom-plate cells.")
    a("* GENERATED by size_seq.py from data/sizing.json (N = %d delay cells per stage);" % n)
    a("* never hand-edit. SPEC.md has the requirements, README.md the record.")
    a("*")
    a("* In: clk, the 20 MHz count clock (ADR 0024); acq, the controller's acquire")
    a("* level (1 = track). Out: per cell k the switch controls, HIGH = closed:")
    a("*   s2_k  bottom plate to vref (S2), opens first: the sampling instant")
    a("*   s0_k  input gate (S0), opens after s2_k")
    a("*   s1_k  ramp connect (S1), closes after s0_k opens, opens first on re-entry")
    a("*")
    a("* Structure (ADR 0029): a four-flop shift register on clk turns acq into one")
    a("* track level per cell, t_k, falling at the k-th rising edge after the edge")
    a("* that sees acq low (cells one period, 50 ns, apart). Each t_k drives one")
    a("* seq_clkgen: the EE628 two-phase non-overlapping clock generator")
    a("* (B. Murmann, template_clkgen.sch), cross-coupled NAND pair with the early")
    a("* phases, in the same gates, with a short delay stage D (seq_dly, N x inv_2)")
    a("* added in three of its paths so every dead time is at least the template's")
    a("* own four-inverter delay (a few hundred ps, ADR 0031):")
    a("*   p1e -> s2   phase-1 early: opens first (bottom-plate sampling)")
    a("*   p1  -> s0   phase 1: opens D later (D before b1)")
    a("*   p2e -> s1   phase-2 early: closes D after p1 opens (D after nand2),")
    a("*               opens first on re-entry, p1 closes D later (D before b2)")
    a("* The late phase 2 (p2) of the template has no switch here and is not built.")
    a("*")
    a("* Supplies: vdd / vss are the digital supply (DVDD); the cells' well pins")
    a("* are tied inside. The outputs drive atop_cell's control inputs (AVDD gates).")
    a("* Needs, before this file:")
    a("*   .include /foss/pdk_libs/gf180mcuD/libs.ref/gf180mcu_as_sc_mcu7t3v3/spice/gf180mcu_as_sc_mcu7t3v3.spice")
    a("")
    a(".subckt seq_dly a y vdd vss")
    a("*.PININFO a:I y:O vdd:B vss:B")
    nodes = ["a"] + ["d%d" % i for i in range(1, n)] + ["y"]
    for i in range(n):
        a("XD%d vdd vdd vss vss %s %s %s" % (i + 1, nodes[i + 1], nodes[i], DLY_CELL))
    a(".ends seq_dly")
    a("")
    a(".subckt seq_clkgen clkin p1e p1 p2e vdd vss")
    a("*.PININFO clkin:I p1e:O p1:O p2e:O vdd:B vss:B")
    a("* input buffers (inv_2: Y A)")
    a(g("XI1", "inv_2", "clkinb", "clkin"))
    a(g("XI2", "inv_2", "clkinbb", "clkinb"))
    a("* phase 1: nand2 (Y B A), four inverters to a1, p1e, D, b1; p1 = nand(a1, b1)")
    a(g("XN1", "nand2_2", "n1", "b2", "clkinbb"))
    a(g("XI3", "inv_4", "m1", "n1"))
    a(g("XI5", "inv_4", "m2", "m1"))
    a(g("XI7", "inv_4", "m3", "m2"))
    a(g("XI9", "inv_4", "a1", "m3"))
    a(g("XI11", "inv_4", "p1e", "a1"))
    a("XL1 p1e x1 vdd vss seq_dly")
    a(g("XI13", "inv_4", "b1", "x1"))
    a(g("XN3", "nand2_2", "y1", "b1", "a1"))
    a(g("XI15", "inv_4", "y1b", "y1"))
    a(g("XI17", "inv_8", "p1", "y1b"))
    a("* phase 2: nand2, D, four inverters to a2, p2e, D, b2")
    a(g("XN2", "nand2_2", "n2", "b1", "clkinb"))
    a("XL2 n2 n2d vdd vss seq_dly")
    a(g("XI4", "inv_4", "k1", "n2d"))
    a(g("XI6", "inv_4", "k2", "k1"))
    a(g("XI8", "inv_4", "k3", "k2"))
    a(g("XI10", "inv_4", "a2", "k3"))
    a(g("XI12", "inv_4", "p2e", "a2"))
    a("XL3 p2e x2 vdd vss seq_dly")
    a(g("XI14", "inv_4", "b2", "x2"))
    a(".ends seq_clkgen")
    a("")
    ports = " ".join(["s2_%d" % k for k in range(NCELLS)] + ["s0_%d" % k for k in range(NCELLS)]
                     + ["s1_%d" % k for k in range(NCELLS)])
    a(".subckt sample_seq acq clk %s vdd vss" % ports)
    a("*.PININFO acq:I clk:I %s vdd:B vss:B" % " ".join(p + ":O" for p in ports.split()))
    a("* shift register (dfxtp_2: CLK D Q): t_k = track level of cell k")
    tin = "acq"
    for k in range(NCELLS):
        a(g("XF%d" % k, "dfxtp_2", "clk", tin, "t%d" % k))
        tin = "t%d" % k
    a("* one EE628 clock generator per cell")
    for k in range(NCELLS):
        a("XG%d t%d s2_%d s0_%d s1_%d vdd vss seq_clkgen" % (k, k, k, k, k))
    a(".ends sample_seq")
    return "\n".join(L) + "\n"


def write(n):
    with open(os.path.join(BLOCK, "sample_seq.spice"), "w") as h:
        h.write(deck(n))


def main():
    if len(sys.argv) == 3 and sys.argv[1] == "write":
        write(int(sys.argv[2]))
        return
    with open(os.path.join(BLOCK, "data", "sizing.json")) as h:
        write(int(json.load(h)["n_stage"]))


if __name__ == "__main__":
    main()
