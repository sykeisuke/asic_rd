"""Write sample_seq.spice, the sampling sequencer, for N delay cells per stage.

    python3 size_seq.py write N      the deck for N cells per stage (no simulation)
    python3 size_seq.py              re-write the deck from data/sizing.json

The size phase (bench.py size) fits each PVT cell's two gaps to a + b N and
records the smallest N for which every gap is >= GAP_MIN + GAP_MARGIN; it then
calls write(). Nothing else writes the deck; never hand-edit it.
"""
import json
import os
import sys

from seq_common import BLOCK, LIB, NCELLS, DLY_CELL

P = LIB + "__"


def deck(n):
    L = []
    a = L.append
    a("* sample_seq -- the on-chip sampling sequencer of the four bottom-plate cells.")
    a("* GENERATED by size_seq.py from data/sizing.json (N = %d delay cells per stage);" % n)
    a("* never hand-edit. SPEC.md has the requirements, README.md the record.")
    a("*")
    a("* In: clk, the 20 MHz count clock (ADR 0024); acq, the controller's acquire")
    a("* level (1 = track). Out: per cell k the switch controls, HIGH = closed:")
    a("*   s2_k  bottom plate to vref (S2), opens first: the sampling instant")
    a("*   s0_k  input gate (S0), opens one stage delay D after s2_k")
    a("*   s1_k  ramp connect (S1), closes one stage delay D after s0_k")
    a("* Cell k samples at the k-th clock rising edge after the edge that sees acq")
    a("* low: the S2 flops form the token chain, cells one period (50 ns) apart.")
    a("*")
    a("* Timing: one tapped delay line, shared by the four cells:")
    a("*   c0 = gated clk, buffered; c5 = c0 + D; c10 = c5 + D  (D = %d x dlybuff_2)" % n)
    a("* Per cell three rising-edge flops in a pipeline, each sampling the previous")
    a("* phase's state, so a phase can move only after the one before it has moved")
    a("* (the lock-out of a cross-coupled non-overlap generator, here without its")
    a("* dependence on the clock's falling edge):")
    a("*   qa = s2 <- tin at c0      (tin = acq for cell 0, s2 of the cell before)")
    a("*   qb = s0 <- qa  at c5")
    a("*   qc      <- qb  at c10,    s1 = NOR(qc, qa)")
    a("* Entry: s2 falls, s0 falls D later, s1 rises D later. Re-entry (acq high):")
    a("* s1 falls with s2's rise, s0 rises D later (S1 open before S0 closes).")
    a("*")
    a("* Supplies: vdd / vss are the digital supply (DVDD); the cells' well pins")
    a("* are tied inside. The outputs drive atop_cell's control inputs (AVDD gates).")
    a("* Needs, before this file:")
    a("*   .include /foss/pdk_libs/gf180mcuD/libs.ref/gf180mcu_as_sc_mcu7t3v3/spice/gf180mcu_as_sc_mcu7t3v3.spice")
    a("")
    a(".subckt seq_dly a y vdd vss")
    a("*.PININFO a:I y:O vdd:B vss:B")
    nodes = ["a"] + ["d%d" % i for i in range(1, n)] + ["y"]
    for i in range(n):
        a("XD%d vdd vdd vss vss %s %s %s" % (i + 1, nodes[i + 1], nodes[i], DLY_CELL))
    a(".ends seq_dly")
    a("")
    a(".subckt seq_cell tin c0 c5 c10 s2 s0 s1 done vdd vss")
    a("*.PININFO tin:I c0:I c5:I c10:I s2:O s0:O s1:O done:O vdd:B vss:B")
    a("XFA vdd vdd vss vss c0 tin s2 %sdfxtp_2" % P)
    a("XFB vdd vdd vss vss c5 s2 s0 %sdfxtp_2" % P)
    a("XFC vdd vdd vss vss c10 s0 qc %sdfxtp_2" % P)
    a("XNR vdd vdd vss vss s1 qc s2 %snor2_2" % P)
    a("* done = the three flops agree with tin (nothing left to move in this cell)")
    a("XX1 vdd vdd vss vss s2 tin x1 %sxor2_2" % P)
    a("XX2 vdd vdd vss vss s0 s2 x2 %sxor2_2" % P)
    a("XX3 vdd vdd vss vss qc s0 x3 %sxor2_2" % P)
    a("XND vdd vdd vss vss x1 x2 x3 done %snor3_2" % P)
    a(".ends seq_cell")
    a("")
    ports = " ".join(["s2_%d" % k for k in range(NCELLS)] + ["s0_%d" % k for k in range(NCELLS)]
                     + ["s1_%d" % k for k in range(NCELLS)])
    a(".subckt sample_seq acq clk %s vdd vss" % ports)
    a("*.PININFO acq:I clk:I %s vdd:B vss:B" % " ".join(p + ":O" for p in ports.split()))
    a("* clock gate: the line runs only while a cell has something to move (en =")
    a("* NOT all done), so it is quiet through the conversion; en is latched while")
    a("* clk is low (dlxtn_2 is transparent for ENA = 0), gclk = clk AND en_l")
    a("XEN vdd vdd vss vss done_0 done_1 done_2 done_3 en %snand4_2" % P)
    a("XLG vdd vdd vss vss clk en en_l %sdlxtn_2" % P)
    a("XAG vdd vdd vss vss en_l clk gclk %sand2_2" % P)
    a("XB0 vdd vdd vss vss gclk c0 %sclkbuff_4" % P)
    a("XL1 c0 c5r vdd vss seq_dly")
    a("XB5 vdd vdd vss vss c5r c5 %sclkbuff_4" % P)
    a("XL2 c5 c10r vdd vss seq_dly")
    a("XB10 vdd vdd vss vss c10r c10 %sclkbuff_4" % P)
    for k in range(NCELLS):
        tin = "acq" if k == 0 else "s2_%d" % (k - 1)
        a("XC%d %s c0 c5 c10 s2_%d s0_%d s1_%d done_%d vdd vss seq_cell" % (k, tin, k, k, k, k))
    a(".ends sample_seq")
    return "\n".join(L) + "\n"


def write(n):
    with open(os.path.join(BLOCK, "sample_seq.spice"), "w") as h:
        h.write(deck(n))


def main():
    if len(sys.argv) == 3 and sys.argv[1] == "write":
        write(int(sys.argv[2]))
        return
    with open(os.path.join(BLOCK, "data", "sizing.json")) as h:
        write(int(json.load(h)["n_stage"]))


if __name__ == "__main__":
    main()
