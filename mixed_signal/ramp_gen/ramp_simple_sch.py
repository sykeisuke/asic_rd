#!/usr/bin/env python3
"""Emit the routed xschem drawing ramp_simple.sch and its symbol ramp_simple.sym
(the comparison baseline: current source + capacitor + reset switch).

    ./container.sh 'python3 ramp_simple_sch.py'

Sizes are the {RS_*} parameters of data/ramp_simple_params.spice
(size_simple.py). check-schematic.awk -v sub=ramp_simple proves the drawing
netlists back to ramp_simple.spice. The symbol is pin-compatible with
ramp_gen.sym, so the four-cell testbench takes either.

The annotation (summary box, device values) is text only: it reads the sizes
and the operating point size_simple.py recorded in data/sizing_simple.json
(the same numbers appear as simple_size_* in runs/ramp-gen/<stamp>/metrics.json)
and the in-transient figures of the ramp-gen record named in REC below.
"""
import json
import os

from sch_lib import Sheet, ramp_symbol

BLOCK = os.path.dirname(os.path.abspath(__file__))
SZ = json.load(open(os.path.join(BLOCK, "data", "sizing_simple.json")))
PR, PD = SZ["params"], SZ["predicted"]
REC = "runs/ramp-gen/20261003T001715Z"          # the record holding simple_size_* and simple_nom_*
CW = float(PR["RS_CW"].rstrip("u"))              # MIM side, um
C_PF = PD["c"] * 1e12                            # PDK model value (size_simple.py, AC at 1 kHz)
C_FORMULA_PF = (1.99 * CW * CW + 0.2383 * 4 * CW) / 1000   # 1.99 fF/um2 area + 0.238 fF/um perimeter


def box(s, x, y, title, lines, tsize=0.7, size=0.4, width=None):
    """A framed text block: title line, then body lines; frame drawn as layer-4 lines."""
    s.T(title, x + 20, y + 15, tsize)
    body_y = y + 15 + int(60 * tsize)
    s.T("\n".join(lines), x + 20, body_y, size)
    w = width or int(max([len(title) * 28 * tsize] + [len(l) * 30 * size for l in lines])) + 60
    h = body_y - y + int(58 * size * len(lines)) + 32
    for x1, y1, x2, y2 in ((x, y, x + w, y), (x + w, y, x + w, y + h), (x + w, y + h, x, y + h), (x, y + h, x, y)):
        s.texts.append("L 4 %d %d %d %d {}" % (x1, y1, x2, y2))
    return h


s = Sheet()
box(s, 0, -1060, "ramp_simple -- simple Wilkinson ramp: PMOS current source + %.2f pF MIM + reset switch" % C_PF, [
    "Function: the single-slope ramp of the 8-bit bottom-plate ADC, the comparison baseline for ramp_gen (Miller integrator).",
    "   vramp = vrlo + I t / C; slope 1.5 V / (256 x 50 ns) = 117.2 mV/us (1 LSB = 5.859 mV per 50 ns count).",
    "Pins (subckt order): vramp out (to every cell's S1), rst in (high = reset), vrlo in (start level 0.5 V, must sink I and",
    "   the S1 charge), pbias in (gate bias of the slave source XPS), vdd, vss.   Supply: AVDD = 3.3 V.",
    "Bias: XPS mirrors pbias of the ramp's OWN bias generator (bench: bias_gen; in Analog_top: bias_gen current into an",
    "   L 1 um diode, where the operating point differs from the values on this sheet).",
    "Choices: L 8 um for output impedance and flicker area (the whole 1.6 V swing sits across XPS); the same 4 pF MIM, slope",
    "   and bias as ramp_gen; W bisected at vramp = 1.3 V, then trimmed once on the transient slope (size_simple.py).",
    "Recorded (%s, typical 27 C, 4 cells): INL 0.096 LSB (bow), slope error -0.02 %%," % REC,
    "   -2.9 / -12.9 % with 16 / 64 cells of load; meets 12 of the 20 shared ramp requirements (ramp_gen 20); COMPARISON.md.",
    "Reproduce: make ramp-gen (phase simple: sizing, netlist-back, benches).  Sizes: data/ramp_simple_params.spice.",
    "Generated by ramp_simple_sch.py -- regenerate, do not hand-edit.  No ADR (a baseline, not a candidate).",
])
for i, (kind, net) in enumerate((("opin", "vramp"), ("ipin", "rst"), ("ipin", "vrlo"), ("ipin", "pbias"),
                                 ("iopin", "vdd"), ("iopin", "vss"))):
    s.port(kind, 20, -480 + 40 * i, net)
s.W((320, -560), (480, -560)); s.lab(480, -560, "vdd")
t = s.mos("pfet_03v3", "XPS", 300, -440, "{RS_LPS}", "{RS_WPS}", "{RS_NFPS}")
s.W(t["s"], (320, -560)); s.lab(*t["g"], "pbias", right=False); s.lab(*t["b"], "vdd")
s.W(t["d"], (320, -300), (900, -300)); s.lab(900, -300, "vramp")
cr = s.mim("XCR", 460, -180, "{RS_CW}")
s.W(cr[0], (460, -300)); s.W(cr[1], (460, 0)); s.lab(460, 0, "vss")
t = s.mos("nfet_03v3", "XRST", 700, -180, "0.28u", "{RS_WRST}", "1")
s.W(t["d"], (720, -300)); s.lab(*t["b"], "vss")
s.W(t["s"], (720, -60)); s.lab(720, -60, "vrlo")
s.W(t["g"], (640, -180)); s.lab(640, -180, "rst", right=False)
s.T("current source", 220, -640, 0.45, 13)
s.T("integrating capacitor", 380, -380, 0.35, 13)
s.T("reset to vrlo", 680, -380, 0.35, 13)

# short value tags next to the devices
s.T("Id %.3f uA, gm/Id %.1f S/A" % (PD["i_op_mid"] * 1e6, PD["gm_over_id"]), 340, -545, 0.35, 4)
s.T("C = %.2f pF" % C_PF, 480, -140, 0.45, 4)
s.T("switch: Ron not recorded", 740, -125, 0.32, 4)

# device notes, right of the circuit
NX = 1000
box(s, NX, -650, "XPS -- current source (pfet_03v3)", [
    "L %s  W %s  nf %s  (data/ramp_simple_params.spice)" % (PR["RS_LPS"], PR["RS_WPS"], PR["RS_NFPS"]),
    "Id %.3f uA   gm/Id %.2f S/A   rout %.0f Mohm" % (PD["i_op_mid"] * 1e6, PD["gm_over_id"], PD["rout_mohm"]),
    "   DC op at vramp = 1.3 V (mid-ramp) on bias_gen, typical 27 C",
    "   (size_simple.py -> data/sizing_simple.json = simple_size_* in %s)" % REC,
    "In the ramp transient: mean Id 0.475 uA; at the overrange top",
    "   |Vds| 1.18 V against Vdsat 0.09 V (margin 1.09 V, simple_nom_ps_*)",
    "Predicted bow from gds over the 1.6 V swing: %.2f LSB" % PD["bow_pred_lsb"],
], tsize=0.5, size=0.38)
box(s, NX, -395, "XCR -- integrating capacitor", [
    "cap_mim_2f0_m4m5_noshield, %.1f x %.1f um" % (CW, CW),
    "C = %.3f pF: PDK model (mimcap_typical), AC at 1 kHz, 0.8 V bias" % C_PF,
    "   (size_simple.py; simple_size_c in %s)" % REC,
    "check: 1.99 fF/um2 x area + 0.238 fF/um x perimeter = %.3f pF" % C_FORMULA_PF,
    "Slope current I = C x SLOPE = %.4f uA (before the transient trim)" % (PD["i_target"] * 1e6),
], tsize=0.5, size=0.38)
box(s, NX, -195, "XRST -- reset switch (nfet_03v3)", [
    "W %s  L 0.28u  nf 1; rst high shorts vramp to vrlo" % PR["RS_WRST"],
    "Ron and gm/Id: not recorded (a switch, off during the ramp)",
    "channel charge ~1.4 fC = ~0.2 mV pedestal on 4 pF (same switch",
    "   as ramp_gen's XRST: ramp_gen/DESIGN_RECIPE.md s.3, derived)",
], tsize=0.5, size=0.38)

nseg, njun = s.write(os.path.join(BLOCK, "ramp_simple.sch"))
ramp_symbol(os.path.join(BLOCK, "ramp_simple.sym"),
            "Simple Wilkinson ramp (ramp_simple.spice): PMOS current source + 4 pF MIM + reset switch, the comparison "
            "baseline for ramp_gen. type=subcircuit: xschem descends into ramp_simple.sch.", "XRG", "I + C")
print("PASS: ramp_simple_sch.py wrote ramp_simple.sch (%d wire segments, %d junctions) and ramp_simple.sym" % (nseg, njun))
