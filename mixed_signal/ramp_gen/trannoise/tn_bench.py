"""Write one VACASK transient-noise bench of the four-cell system.

    python3 tn_bench.py <out.sim> <netlist.inc> <nper> <seed> <noisescale> <fmin> <fmax>

The circuit is tb_ramp_adc4's with the real ramp: supply (powered at t = 0,
3.3 V), vrlo 0.5 V, bias_gen (cells), two midref_b, bias_gen_r + ramp_gen,
four unit_cell_bps cells at DC levels (codes 16.5, 80.5, 160.5, 240.5),
50 fF on every dout. The conversion repeats NPER times on one shared
timeline (explicit PWL edges, so the cold start is not periodic):

  0 .. TS0 = 7.3 us   track, rst high (the FVF divider settles, ~7 us)
  per period n, TS = TS0 + n P:
    TS          S2 opens (the sample)       TS + 5 ns   S0 opens
    TS + 10 ns  S1 closes                    TR = TS + 100 ns  rst falls, the count starts
    TE = TR + 276 TCOUNT  (256 codes + 20 overrun): S1 opens, rst rises 5 ns later,
    S0/S2 close 10 ns later; track and ramp recovery for TREC until the next TS
  P = 100 ns + 13.8 us + 10 ns + TREC, TREC = 1.29 us -> P = 15.2 us
"""
import sys

VDD = 3.3
TPWR = 100e-9
TS0 = 7.3e-6
P = 15.2e-6
TCOUNT = 50e-9
NCOUNT = 276
TEDGE = 100e-12
LSB = 1.5 / 256
POS = (16.5, 80.5, 160.5, 240.5)


def timeline(nper):
    """Per-period edge times (relative to TS of that period)."""
    tr = 100e-9
    te = tr + NCOUNT * TCOUNT
    return dict(s2_open=0.0, s0_open=5e-9, s1_close=10e-9, rst_fall=tr, s1_open=te,
                rst_rise=te + 5e-9, s02_close=te + 10e-9)


def pwl(points):
    return "[" + ", ".join("%.12g, %.6g" % (t, v) for t, v in points) + "]"


def waves(nper):
    e = timeline(nper)
    s2 = [(0, VDD)]
    s0 = [(0, VDD)]
    s1 = [(0, 0)]
    rst = [(0, VDD)]
    for n in range(nper):
        ts = TS0 + n * P
        s2 += [(ts + e["s2_open"], VDD), (ts + e["s2_open"] + TEDGE, 0),
               (ts + e["s02_close"], 0), (ts + e["s02_close"] + TEDGE, VDD)]
        s0 += [(ts + e["s0_open"], VDD), (ts + e["s0_open"] + TEDGE, 0),
               (ts + e["s02_close"], 0), (ts + e["s02_close"] + TEDGE, VDD)]
        s1 += [(ts + e["s1_close"], 0), (ts + e["s1_close"] + TEDGE, VDD),
               (ts + e["s1_open"], VDD), (ts + e["s1_open"] + TEDGE, 0)]
        rst += [(ts + e["rst_fall"], VDD), (ts + e["rst_fall"] + TEDGE, 0),
                (ts + e["rst_rise"], 0), (ts + e["rst_rise"] + TEDGE, VDD)]
    return s0, s1, s2, rst


def main():
    out, net, nper, seed, scale, fmin, fmax = sys.argv[1:8]
    nper, seed = int(nper), int(seed)
    s0, s1, s2, rst = waves(nper)
    stop = TS0 + nper * P
    lines = ["Ramp generator + four bottom-plate cells, VACASK transient noise", "",
             "// GENERATED by trannoise/tn_bench.py", "ground 0",
             'include "../models.inc"', 'include "%s"' % net,
             'load "resistor.osdi"', 'load "capacitor.osdi"',
             "model resistor resistor", "model capacitor capacitor", "model vsource vsource", "",
             "vdd (vdd 0) vsource dc=%.6g" % VDD,
             "vrlo (vrlo 0) vsource dc=0.5",
             "vclk (clk 0) vsource dc=0",
             'vs0 (s0 0) vsource type="pwl" wave=%s' % pwl(s0),
             'vs1 (s1 0) vsource type="pwl" wave=%s' % pwl(s1),
             'vs2 (s2 0) vsource type="pwl" wave=%s' % pwl(s2),
             'vrst (rst 0) vsource type="pwl" wave=%s' % pwl(rst),
             "xbias (vdd 0 pbias nbias) bias_gen",
             "xvref (vref pbias vdd 0) midref_b",
             "xvbl (vbl pbias vdd 0) midref_b",
             "// the ramp has its own bias generator (pbias_r): a comparator decision glitches the",
             "// cells' pbias by ~0.5 mV, which a shared line would carry into the slope current",
             "xbiasr (vdd 0 pbias_r nbias_r) bias_gen_r",
             "xrg (vramp rst vrlo pbias_r vdd 0) ramp_gen"]
    for i, p in enumerate(POS):
        lines += ["vin%d (vin%d 0) vsource dc=%.9g" % (i, i, 0.5 + p * LSB),
                  "xc%d (vin%d vramp s0 s1 s2 vref vbl dout%d clk pbias nbias vdd 0) unit_cell_bps" % (i, i, i),
                  "cl%d (dout%d 0) capacitor c=50f" % (i, i)]
    lines += ["", "control", "  var mm=0",
              "  // tran_noiselte=3: the default floor (1) collapses the step at once with every",
              "  // group noisy; 2 runs a period but aborts some seeds, 3 is used. tran_extraoct=0: the",
              "  // flicker Lorentzians stop at noisefmin, the band tn_predict.py models.",
              "  options temp=27 tnom=27 gmin=1e-15 tran_extraoct=0 tran_noiselte=3",
              "  save v(vramp) v(dout0) v(dout1) v(dout2) v(dout3) v(vbl) v(pbias)",
              '  analysis tn tran stop=%.9g step=1n noisemode="sde" noisefmax=%s noisefmin=%s noiseseed=%d noisescale=%s'
              % (stop, fmax, fmin, seed, scale), "endc", ""]
    open(out, "w").write("\n".join(lines))


if __name__ == "__main__":
    main()
