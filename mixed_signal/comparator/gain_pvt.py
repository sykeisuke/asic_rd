"""gain_pvt.py -- the whole comparator's gain (inn -> dout) over PVT on the real bias
(run-pvt.sh phase `gain`, in the container, cwd = this block).

One point per cell of bias_gen's 135-cell verification (../bias_gen/data/
verify_op.csv: 5 corners x 0/27/85 C x 3.0/3.3/3.6 V x resistor typ/ss/ff): the
comparator deck at that corner, temperature and supply, with that cell's comparator
current `ic` as the ideal bias into its 1 um / 0.28 um diode; inp = VDD/2.
The gain is the peak DC slope of dout through the trip: a coarse sweep finds the
trip, a 0.5 uV sweep over +-1 mV around it gives d dout / d inn.
Static converting power at the same cell: AVDD x (comparator supply + the diode's ic) with
inn 50 mV below / above the trip (dout settled low / high), the larger of the two; the
nbias diode of the deck (not in the macro) is excluded. Reported, not gated.

Gate: the minimum over the 135 points >= GAIN_SPEC_DB (60 dB, user 2026-10-15).
Writes data/gain_pvt.csv; prints gain_pvt_min_db / _max_db and PASS/FAIL.
"""
import csv
import math
import os
import re
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
W = os.path.join(HERE, "work", "gain_pvt")
GAIN_SPEC_DB = 60.0
JOBS = int(os.environ.get("JOBS", "14"))
BG = os.path.join(HERE, "..", "bias_gen", "data", "verify_op.csv")

DECK = """* gain_pvt -- GENERATED by gain_pvt.py
.include /foss/pdks/gf180mcuD/libs.tech/ngspice/design.ngspice
.lib /foss/pdks/gf180mcuD/libs.tech/ngspice/sm141064.ngspice {corner}
.include {block}/comparator.spice
.param VDD={vdd}
.param IREF={iref}
.temp {temp}
.options reltol=1e-6 vntol=1e-9 abstol=1e-15
VDD_SOURCE vdd 0 {{VDD}}
VDD_BIAS vddb 0 {{VDD}}
IREFN vddb nbias {{IREF}}
XREFN nbias nbias 0 0 nfet_03v3 L=1u W=20u nf=10 m=1
IREFP pbias 0 {{IREF}}
XREFP pbias pbias vddb vddb pfet_03v3 L=0.28u W=1u nf=1 m=1
VCLK clk 0 0
VVBL vbl 0 {{VDD/2}}
VINN inn 0 {{VDD/2}}
XDUT vbl inn dout clk vdd 0 nbias pbias cmp
CL dout 0 10f
.control
dc VINN {lo} {hi} 1e-4
meas dc vt when v(dout)={half} fall=1
set vts = "$&vt"
let a = vt - 1e-3
let b = vt + 1e-3
let c = vt - 0.05
let e = vt + 0.05
set cs = "$&c"
set es = "$&e"
dc VINN $&a $&b 5e-7
wrdata fine.txt v(dout)
dc VINN $cs $es 0.0999
wrdata conv.txt i(VDD_SOURCE)
echo "vtrip = $vts"
quit
.endc
.end
"""


def run(i, row):
    d = os.path.join(W, "p%03d" % i)
    os.makedirs(d, exist_ok=True)
    open(os.path.join(d, ".spiceinit"), "w").write("set num_threads=1\n")
    vdd = float(row["vdd"])
    deck = DECK.format(corner=row["corner"], block="/foss/designs/mixed_signal/comparator",
                       vdd=vdd, iref="%.6g" % float(row["ic"]), temp=row["temp"],
                       lo=vdd / 2 - 0.03, hi=vdd / 2 + 0.03, half=vdd / 2)
    open(os.path.join(d, "tb.spice"), "w", newline="\n").write(deck)
    r = subprocess.run(["ngspice", "-b", "tb.spice"], cwd=d, capture_output=True, text=True)
    m = re.search(r"vtrip = ([-+0-9.eE]+)", r.stdout)
    f = os.path.join(d, "fine.txt")
    if r.returncode or not m or not os.path.exists(f):
        return dict(row, gain_vv=float("nan"), gain_db=float("nan"), vtrip=float("nan"), p_conv_uw=float("nan"))
    dc = np.loadtxt(f)
    a = float(np.max(np.abs(np.gradient(dc[:, 1], dc[:, 0]))))
    cv = np.atleast_2d(np.loadtxt(os.path.join(d, "conv.txt")))
    p = vdd * (float(np.max(np.abs(cv[:, 1]))) + float(row["ic"])) * 1e6
    return dict(row, gain_vv=a, gain_db=20 * math.log10(a), vtrip=float(m.group(1)), p_conv_uw=p)


def main():
    rows = list(csv.DictReader(open(BG)))
    os.makedirs(W, exist_ok=True)
    with ThreadPoolExecutor(JOBS) as ex:
        res = list(ex.map(lambda ir: run(*ir), enumerate(rows)))
    keys = ["corner", "temp", "rcorner", "vdd", "ic", "vtrip", "gain_vv", "gain_db", "p_conv_uw"]
    os.makedirs(os.path.join(HERE, "data"), exist_ok=True)
    with open(os.path.join(HERE, "data", "gain_pvt.csv"), "w", newline="") as fh:
        wr = csv.writer(fh)
        wr.writerow(keys)
        for r in res:
            wr.writerow([r[k] for k in keys])
    ok = [r for r in res if not math.isnan(r["gain_db"])]
    if len(ok) != len(res):
        print("FAIL: gain_pvt: %d of %d points did not simulate" % (len(res) - len(ok), len(res)))
    lo = min(ok, key=lambda r: r["gain_db"])
    hi = max(ok, key=lambda r: r["gain_db"])
    print("gain_pvt_points = %d" % len(ok))
    print("gain_pvt_min_db = %.2f" % lo["gain_db"])
    print("gain_pvt_max_db = %.2f" % hi["gain_db"])
    print("REPORT: gain_pvt: inn -> dout %.1f-%.1f dB over %d cells (min at %s/%s C/%s/%s V, bias %.2f uA;"
          " max at %s/%s C/%s/%s V, bias %.2f uA)"
          % (lo["gain_db"], hi["gain_db"], len(ok), lo["corner"], lo["temp"], lo["rcorner"], lo["vdd"],
             float(lo["ic"]) * 1e6, hi["corner"], hi["temp"], hi["rcorner"], hi["vdd"], float(hi["ic"]) * 1e6))
    pw = [r for r in ok if not math.isnan(r["p_conv_uw"])]
    pmax = max(pw, key=lambda r: r["p_conv_uw"])
    print("conv_pvt_max_uw = %.2f" % pmax["p_conv_uw"])
    print("conv_pvt_min_uw = %.2f" % min(r["p_conv_uw"] for r in pw))
    print("REPORT: conv_pvt: static converting power %.1f-%.1f uW over %d cells (max at %s/%s C/%s/%s V, bias %.2f uA)"
          % (min(r["p_conv_uw"] for r in pw), pmax["p_conv_uw"], len(pw), pmax["corner"], pmax["temp"],
             pmax["rcorner"], pmax["vdd"], float(pmax["ic"]) * 1e6))
    good = lo["gain_db"] >= GAIN_SPEC_DB and len(ok) == len(res)
    print("%s: gain_pvt: minimum %.1f dB >= %.0f dB over the bias generator's PVT cells"
          % ("PASS" if good else "FAIL", lo["gain_db"], GAIN_SPEC_DB))
    return 0 if good else 1


if __name__ == "__main__":
    sys.exit(main())
