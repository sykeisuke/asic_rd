"""Generate comparator.spice (and the macro form comparator_d.spice) from
comparator_core.spice. Never hand-edit the outputs.

    ./container.sh 'python3 derive.py'           write both netlists
    ./container.sh 'python3 derive.py --check'   regenerate in memory, compare, print PASS/FAIL

What changes against the source subcircuit `comparator_core`:
  - the 10 sized devices are copied line for line, except that the old output
    node `dout` is renamed `outc`;
  - one more inverter drives `dout`: XBUF5 (nfet) / XBUF6 (pfet), copies of
    XBUF3 / XBUF4 with gate outc and drain dout (L 0.36 um, W 0.5 / 1 um);
  - the subcircuit is `comparator`, same port list as `comparator_core`
    (inp inn dout clk vdd vss nbias pbias).
Use: the moving (floating) plate on inp, the reference VREF on inn; dout FALLS
when inp rises through inn, as the core's dout falls when inn rises through
inp. The macro form `comparator_d` (inp inn ibias dout vdd vss) is the
same 12 devices plus the cell's bias diode XREFP (one tail finger), pbias -> ibias,
the form Analog_top's comparator_d uses.
"""
import os
import re
import sys

BLOCK = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(BLOCK, "comparator_core.spice")
OUT = os.path.join(BLOCK, "comparator.spice")
OUT_D = os.path.join(BLOCK, "comparator_d.spice")
PORTS = "inp inn dout clk vdd vss nbias pbias"


def source_devices():
    text = open(SRC).read()
    body = text[text.index(".subckt comparator_core"):text.index(".ends")]
    lines = [l.strip() for l in body.splitlines()[1:] if l.strip() and not l.startswith("*")]
    head = text[:text.index(".subckt comparator_core")].splitlines()
    if body.splitlines()[0].split()[2:] != PORTS.split():
        raise SystemExit("FAIL: derive: comparator_core.spice port list changed")
    return lines, head


def rename(line, old, new):
    t = line.split()
    # name d g s b model params: rename node fields only (1..4)
    t[1:5] = [new if x == old else x for x in t[1:5]]
    return " ".join(t)


def devices():
    src, head = source_devices()
    dev = [rename(l, "dout", "outc") for l in src]
    by = {l.split()[0]: l for l in dev}
    if "XBUF3" not in by or "XBUF4" not in by:
        raise SystemExit("FAIL: derive: XBUF3 / XBUF4 not found in the source")
    b3 = by["XBUF3"].split()
    b4 = by["XBUF4"].split()
    # XBUF3: outc outb vss vss nfet ...; XBUF4: outc outb vdd vdd pfet ...
    b5 = ["XBUF5", "dout", "outc"] + b3[3:]
    b6 = ["XBUF6", "dout", "outc"] + b4[3:]
    return src, dev + [" ".join(b5), " ".join(b6)], head


def header(src_head, form):
    sha = __import__("hashlib").sha256(open(SRC, "rb").read()).hexdigest()[:16]
    return "\n".join([
        f"* {form} -- the comparator: the sized core comparator_core plus one more",
        "* output inverter: PMOS 5T OTA -> starved inverter -> inverter -> inverter",
        "* (12 devices). Use: the floating plate on inp, VREF on inn; dout FALLS when",
        "* inp rises through inn (the core's dout falls when inn rises through inp).",
        "* The 10 sized devices are comparator_core.spice's, unchanged; its",
        "* old output node is outc here. XBUF5 / XBUF6 copy XBUF3 / XBUF4.",
        f"* GENERATED by derive.py from comparator_core.spice (sha256 {sha}...).",
        "* Do not hand-edit.",
    ])


def emit():
    src, dev, head = devices()
    a = header(head, "comparator") + "\n" + f".subckt comparator {PORTS}\n" + "\n".join(dev) + "\n.ends comparator\n"
    dd = []
    for l in dev:
        t = l.split()
        t[1:5] = ["ibias" if x == "pbias" else x for x in t[1:5]]
        dd.append(" ".join(t))
    tail = [l for l in dev if l.split()[0] == "XTAIL"][0].split()
    lm = re.search(r"L=(\S+)", " ".join(tail)).group(1)
    nf = int(re.search(r"nf=(\d+)", " ".join(tail)).group(1))
    wt = float(re.search(r"W=([0-9.]+)u", " ".join(tail)).group(1))
    wf = wt / nf
    dd.append(f"XREFP ibias ibias vdd vdd pfet_03v3 L={lm} W={wf:g}u nf=1 m=1")
    b = (header(head, "comparator_d") + "\n* Macro form: the cell's bias diode XREFP inside, ports inp inn ibias dout vdd vss\n"
         + ".subckt comparator_d inp inn ibias dout vdd vss\n" + "\n".join(dd) + "\n.ends comparator_d\n")
    return src, dev, a, b


def main():
    src, dev, a, b = emit()
    if "--check" in sys.argv:
        ok = True
        for path, want in ((OUT, a), (OUT_D, b)):
            have = open(path).read() if os.path.exists(path) else ""
            good = have == want
            ok &= good
            print(f"{'PASS' if good else 'FAIL'}: netlist: {os.path.basename(path)} is what derive.py generates from "
                  f"comparator_core.spice")
        same = [d for d in dev[:10]]
        exp = [rename(l, "dout", "outc") for l in src]
        good = same == exp and len(dev) == 12 and len(src) == 10
        ok &= good
        print(f"{'PASS' if good else 'FAIL'}: netlist: the 10 sized devices equal the source's, dout renamed outc; "
              f"2 added (XBUF5 / XBUF6)")
        print(f"comparator_devices = {len(dev)}")
        return 0 if ok else 1
    open(OUT, "w").write(a)
    open(OUT_D, "w").write(b)
    print(f"wrote {OUT} and {OUT_D}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
