"""Translate the comparator subcircuit (ngspice) into a VACASK subcircuit.

    python3 vacask_lib/spice2sim.py comparator.spice work/dut.inc

Deliberately narrow: it accepts exactly the constructs the generated
`comparator.spice` uses -- one `.subckt`, `X` instances of nfet_03v3/pfet_03v3
with L/W/nf/m, `C` capacitors with a plain value -- and fails loudly on
anything else, so a netlist change that this translator does not understand
cannot pass through silently. The VACASK side keeps every node and instance
name in lower case (VACASK lower-cases OSDI names; the netlist names are
lower-cased here for consistency), so `xdut:outa` and `xdut:xinp` address the
same things `xdut.outa` and `xdut.xinp` do in ngspice.
"""
import re
import sys

DEV = {"nfet_03v3", "pfet_03v3"}
SI = {"f": 1e-15, "p": 1e-12, "n": 1e-9, "u": 1e-6, "m": 1e-3, "k": 1e3, "meg": 1e6, "g": 1e9, "t": 1e12}


def num(tok):
    m = re.match(r"^([-+]?[0-9.]+(?:[eE][-+]?\d+)?)(meg|[fpnumkgt])?[a-zA-Z]*$", tok)
    if not m:
        raise SystemExit(f"FAIL: spice2sim cannot parse number {tok!r}")
    return float(m.group(1)) * SI.get((m.group(2) or "").lower(), 1.0)


def main():
    src, dst = sys.argv[1], sys.argv[2]
    out, name, ports = [], None, None
    with open(src) as f:
        for raw in f:
            line = raw.strip()
            if not line or line.startswith("*"):
                continue
            low = line.lower()
            if low.startswith(".subckt"):
                parts = line.split()
                name, ports = parts[1].lower(), [p.lower() for p in parts[2:]]
                out.append(f"subckt {name} ({' '.join(ports)})")
                continue
            if low.startswith(".ends"):
                out.append("ends")
                continue
            parts = line.split()
            ref = parts[0].lower()
            if ref.startswith("x"):
                nodes = [p.lower() for p in parts[1:5]]
                dev = parts[5].lower()
                if dev not in DEV:
                    raise SystemExit(f"FAIL: spice2sim: unknown device {dev} in {line!r}")
                params = []
                for tok in parts[6:]:
                    k, v = tok.split("=", 1)
                    if k.lower() not in ("l", "w", "nf", "m"):
                        raise SystemExit(f"FAIL: spice2sim: unexpected parameter {k} in {line!r}")
                    if "{" in v:
                        raise SystemExit(f"FAIL: spice2sim: expression {v} not supported in {line!r}")
                    params.append(f"{k.lower()}={num(v):.6g}")
                out.append(f"  {ref} ({' '.join(nodes)}) {dev} {' '.join(params)}")
            elif ref.startswith("c"):
                a, b, val = parts[1].lower(), parts[2].lower(), num(parts[3])
                out.append(f"  {ref} ({a} {b}) capacitor c={val:.6g}")
            else:
                raise SystemExit(f"FAIL: spice2sim: unsupported line {line!r}")
    if name is None:
        raise SystemExit("FAIL: spice2sim: no .subckt found")
    with open(dst, "w") as f:
        f.write(f"// GENERATED by vacask_lib/spice2sim.py from {src}; do not edit.\n")
        f.write("// Requires: load \"capacitor.osdi\", model capacitor capacitor, the GF180 include.\n")
        f.write("\n".join(out) + "\n")
    print(f"INFO: wrote {dst} ({name}, ports {' '.join(ports)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
