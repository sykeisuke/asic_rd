def mimcorner(c):
    return c if c in ("ff", "ss") else "typical"


def fmt(x):
    return ("%.4f" % x).rstrip("0").rstrip(".")


def mos(name, d, g, s, b, kind, L, wf, nf):
    """One multi-finger device with the S/D geometry the PDK xschem symbols write."""
    nf = int(nf)
    # the model's W bin ends at 100 um: split into m identical instances (nf divisible by m)
    m = max(1, int(np.ceil(nf * wf / W_BIN_MAX - 1e-9)))
    while nf % m:
        m += 1
    nf //= m
    w = nf * wf
    nd, ns = (nf + 1) // 2, (nf + 2) // 2
    return (f"{name} {d} {g} {s} {b} {kind} L={fmt(L)}u W={fmt(w)}u nf={nf} m={m}"
            f" ad={nd * wf * SD_EXT:.4g}p pd={2 * nd * (wf + SD_EXT):.4g}u"
            f" as={ns * wf * SD_EXT:.4g}p ps={2 * ns * (wf + SD_EXT):.4g}u"
            f" nrd={SD_EXT / w:.4g} nrs={SD_EXT / w:.4g}")


PORTS = "vdd vss icmp0 icmp1 icmp2 icmp3 iramp ivref ivbl"


def netlist(s, name="bias_gen", export=False, kick=True):
    """The generator from a sizing dict s (keys: L, wf, K, na, npm, nc, nr, nm,
    nbl, rseg, rlen, cpb, cnb). Topology:

      core   XMN1 diode (na) / XMN2 (K na, degenerated by XR) / XMP1, XMP2 (npm, 1:1)
      sinks  XOC0..3 (nc each), XOR (nr) gate nb -> comparator / ramp diodes
      srcs   XOV, XOB (nm each) gate pb -> the two midref ib diodes
      start  nbl PMOS diodes (bleeder) -> su; XSU4 (gate nb) pulls su down once
             the loop runs; XSU5 (gate su) kicks pb low from the dead state
      decap  MIM pb -> vdd, nb -> vss
    """
    L, wf = s["L"], s["wf"]
    N, P = "nfet_03v3", "pfet_03v3"
    lines = [f".subckt {name} {PORTS}" + (" nb pb su" if export else ""),
             "* ---- core: NMOS-defined beta multiplier",
             mos("XMN1", "nb", "nb", "vss", "vss", N, L, wf, s["na"]),
             mos("XMN2", "pb", "nb", "ns", "vss", N, L, wf, s["K"] * s["na"]),
             mos("XMP1", "nb", "pb", "vdd", "vdd", P, L, wf, s["npm"]),
             mos("XMP2", "pb", "pb", "vdd", "vdd", P, L, wf, s["npm"])]
    nodes = ["ns"] + [f"r{k}" for k in range(1, s["rseg"])] + ["vss"]
    for k in range(s["rseg"]):
        lines.append(f"XR{k + 1} {nodes[k]} {nodes[k + 1]} vss {RES_TYPE} r_width={fmt(RES_W)}u r_length={fmt(s['rlen'])}u")
    lines.append("* ---- output sinks (gate nb) and sources (gate pb)")
    for k in range(N_CMP):
        lines.append(mos(f"XOC{k}", f"icmp{k}", "nb", "vss", "vss", N, L, wf, s["nc"]))
    lines.append(mos("XOR", "iramp", "nb", "vss", "vss", N, L, wf, s["nr"]))
    lines.append(mos("XOV", "ivref", "pb", "vdd", "vdd", P, L, wf, s["nm"]))
    lines.append(mos("XOB", "ivbl", "pb", "vdd", "vdd", P, L, wf, s["nm"]))
    lines.append("* ---- startup: bleeder of PMOS diodes, disengage, kick")
    prev = "vdd"
    for k in range(s["nbl"]):
        nxt = "su" if k == s["nbl"] - 1 else f"sb{k + 1}"
        lines.append(mos(f"XSB{k + 1}", nxt, nxt, prev, "vdd", P, L, wf, 1))
        prev = nxt
    lines.append(mos("XSU4", "su", "nb", "vss", "vss", N, L, wf, 1))
    if kick:
        lines.append(mos("XSU5", "pb", "su", "vss", "vss", N, L, wf, 1))
    lines.append("* ---- decoupling (MIM over the rows)")
    if s.get("cpb", 0) > 0:
        c = np.sqrt(s["cpb"] / MIM_CAP_DENS)
        lines.append(f"XCP vdd pb cap_mim_2f0_m4m5_noshield c_width={fmt(c)}u c_length={fmt(c)}u")
    if s.get("cnb", 0) > 0:
        c = np.sqrt(s["cnb"] / MIM_CAP_DENS)
        lines.append(f"XCN nb vss cap_mim_2f0_m4m5_noshield c_width={fmt(c)}u c_length={fmt(c)}u")
    lines.append(f".ends {name}")
    return "\n".join(lines) + "\n"


def consumer_loads(prefix="", vdd="vdd"):
    """The consumers' own reference diodes, each behind a 0 V ammeter:
    comparator k: vdd -> diode -> lc<k> -> VMC<k> -> icmp<k>; ramp likewise;
    midref: ivref -> VMV -> lv -> NMOS diode -> 0."""
    out = []
    kind, L, wf, nf = CMP_DIODE
    for k in range(N_CMP):
        out.append(mos(f"XLC{k}", f"lc{k}", f"lc{k}", vdd, vdd, kind, L, wf, nf))
        out.append(f"VMC{k} lc{k} icmp{k} 0")
    kind, L, wf, nf = RAMP_DIODE
    out.append(mos("XLR", "lr", "lr", vdd, vdd, kind, L, wf, nf))
    out.append("VMR lr iramp 0")
    kind, L, wf, nf = MR_DIODE
    for tag, port in (("v", "ivref"), ("b", "ivbl")):
        out.append(f"VM{tag.upper()} {port} l{tag} 0")
        out.append(mos(f"XL{tag.upper()}", f"l{tag}", f"l{tag}", "0", "0", kind, L, wf, nf))
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- ngspice
def run(d, deck_text, name="deck.spice", timeout=300):
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, name), "w") as h:
        h.write(deck_text)
    with open(os.path.join(d, ".spiceinit"), "w") as h:    # one OpenMP thread (ngspice-num-threads trap)
        h.write("set num_threads=1\n")
    out = name.replace(".spice", ".out")
    env = dict(os.environ, OMP_NUM_THREADS="1")
    try:
        subprocess.run(["ngspice", "-b", "-o", out, name], cwd=d, env=env, stdin=subprocess.DEVNULL,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=timeout)
        with open(os.path.join(d, out), errors="replace") as h:
            return h.read()
    except (subprocess.TimeoutExpired, OSError):
        return ""


def grab(txt, key):
    m = re.search(r"^\s*%s\s*=\s*([-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?)" % re.escape(key), txt, re.M)
    return float(m.group(1)) if m else float("nan")


def devices(s):
    """(instance, flavour) of every generator MOS, for headroom probes."""
    names = ["xmn1", "xmn2", "xmp1", "xmp2"] + [f"xoc{k}" for k in range(N_CMP)] + ["xor", "xov", "xob"]
    return names


def op_deck(s, cell, rcorner, dut, loads=True, extra=""):
    """Operating point over the three supplies at one corner/temperature/res
    corner. One OP line per supply: currents of every output, core, bleeder,
    nodes, supply current, worst saturation margin of the matched devices."""
    corner, temp = cell
    hr = " ".join(f"$&hr_{n}" for n in devices(s))
    lets = "\n".join(f"  let hr_{n} = abs(@m.xg.{n}.m0[vds]) - abs(@m.xg.{n}.m0[vdsat])" for n in devices(s))
    return (f"* bias_gen operating point\n" + NGSPICE_HEAD.format(corner=corner, rcorner=rcorner, mim=mimcorner(corner))
            + f".temp {temp:g}\n.include {dut}\nVDD vdd 0 3.3\n"
            + f"XG vdd 0 icmp0 icmp1 icmp2 icmp3 iramp ivref ivbl bias_gen\n"
            + (consumer_loads() if loads else "") + extra
            + ".control\nset num_threads=1\n"
            + "foreach v " + " ".join("%g" % v for v in VDDS) + "\n"
            + "  alter VDD dc = $v\n  op\n"
            + "  let ic = abs(i(vmc0))\n  let ic1 = abs(i(vmc1))\n  let ir = abs(i(vmr))\n  let iv = abs(i(vmv))\n"
            + "  let icore = abs(@m.xg.xmn1.m0[id])\n  let ibl = abs(@m.xg.xsu4.m0[id])\n"
            + "  let isup = -i(vdd)\n  let vsu = v(xg.su)\n  let vnb = v(xg.nb)\n  let vpb = v(xg.pb)\n"
            + "  let vlc = v(lc0)\n  let vlr = v(lr)\n  let vlv = v(lv)\n"
            + lets + "\n"
            + f"  echo \"OP {corner} {temp:g} {rcorner} $v $&ic $&ic1 $&ir $&iv $&icore $&ibl $&isup $&vsu $&vnb $&vpb $&vlc $&vlr $&vlv {hr}\"\n"
            + "end\nquit\n.endc\n.end\n")


OP_COLS = ("ic", "ic1", "ir", "iv", "icore", "ibl", "isup", "vsu", "vnb", "vpb", "vlc", "vlr", "vlv")


def parse_op(txt, s):
    rows = []
    for m in re.finditer(r"^OP (\S+) (\S+) (\S+) (\S+) (.*)$", txt, re.M):
        vals = [float(x) for x in m.group(5).split()]
        r = dict(corner=m.group(1), temp=float(m.group(2)), rcorner=m.group(3), vdd=float(m.group(4)))
        r.update(dict(zip(OP_COLS, vals)))
        hrs = vals[len(OP_COLS):]
        r["hr_min"] = min(hrs) if hrs else float("nan")
        r["hr_dev"] = devices(s)[int(np.argmin(hrs))] if hrs else ""
        rows.append(r)
    return rows


def bias_req():
    """{(corner, temp, vdd): required comparator scale} from bias_req.csv (geom=1)."""
    req = {}
    with open(BIAS_REQ_CSV) as h:
        keys = h.readline().strip().split(",")
        for line in h:
            r = dict(zip(keys, line.strip().split(",")))
            if r["geom"] != "1":
                continue
            c, t, v = r["tag"].split("_")
            req[(c, float(t), float(v))] = float(r["req_scale"])
    return req


# ---------------------------------------------------------------- ramp-line noise
NOISE_F_HI = 1.0 / (2 * np.pi * 12.8e-6)       # the ramp integrates its slope current over 12.8 us
RAMP_BIAS_NOISE_OLD_LSB = 0.0807               # [M] ramp_gen data/noise_breakdown.csv, bias_gen group, code 255
