#!/usr/bin/env python3
"""Parasitic extraction of a drawn capacitor, with two engines.

    python3 pex.py MOMU [MOMU2 ...] --spice-dir <dir>

A MOM capacitor has no model card, so extraction is not a refinement of
its value -- extraction *is* its value.  That makes a single extractor a
single point of failure, so both of kpex's engines run on every cell and
their disagreement is reported as a figure of merit:

    FasterCap   3-D boundary-element field solver.  The reference.
    kpex/2.5D   analytical, from the same technology stack description.

Neither is silicon.  What agreement between them buys is confidence that
the number is not an artifact of one engine's meshing or one engine's
closed form; it says nothing about how well either matches the fab.

Three things learned the hard way, all encoded below:

1.  FasterCap's defaults do not converge on a finger array.  The default
    --tolerance 0.05 with --delaunay_amax 50 sits well above the value a
    finer mesh and a tighter tolerance settle on, so the settings below
    are the converged ones, not the fast ones.  `--converge` re-measures
    that on the cell at hand rather than asking anyone to take it on
    trust.
2.  The PDK LVS deck writes its extracted netlist to
    `Pathname("").parent.realpath`, which is the *parent* of the working
    directory.  Run kpex from a subdirectory or the write fails with
    EACCES on `/`.
3.  kpex's dummy schematic declares pins VDD and VSS, which exist in no
    MOM layout, so the extracted subcircuit comes back with no ports at
    all.  The port-bearing netlist this writes for ngspice is built from
    the engine's CSV rather than from its SPICE output.
"""

import argparse
import csv
import os
import subprocess
import sys

BLOCK = os.path.dirname(os.path.abspath(__file__))
WORK = os.path.join(BLOCK, "work")
GDS = os.path.join(BLOCK, "physical", "final_views", "gds")

#- Converged FasterCap settings; see point 1 in the module docstring.
FC_TOLERANCE = "0.005"
FC_AMAX = "10"


def run_kpex(cell, engine, out_dir, gds=None, tolerance=None, amax=None):
    #- kpex is spawned from a subdirectory of out_dir, so a path relative
    #- to the block would not resolve; see point 2 in the module docstring
    gds = os.path.abspath(gds or os.path.join(GDS, cell + ".gds"))
    if not os.path.exists(gds):
        raise SystemExit(f"no GDS for {cell}. Run: make mom-cap")
    cmd = ["kpex", "--pdk", "gf180mcuD", "--gds", gds, "--cell", cell,
           "--out_dir", out_dir]
    if engine == "fastercap":
        cmd += ["--fastercap",
                "--tolerance", tolerance or FC_TOLERANCE,
                "-a", amax or FC_AMAX]
    else:
        cmd += ["--2.5D"]
    #- see point 2: a subdirectory, so the deck's parent-of-cwd write lands
    #- somewhere writable
    cwd = os.path.join(out_dir, "run")
    os.makedirs(cwd, exist_ok=True)
    r = subprocess.run(cmd, cwd=cwd, text=True,
                       stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    log = os.path.join(WORK, f"{cell}-{engine}.log")
    with open(log, "w") as fo:
        fo.write(r.stdout)
    if r.returncode != 0:
        raise SystemExit(f"kpex {engine} failed on {cell}; see {log}")
    return out_dir


def read_caps(out_dir, cell, engine):
    """Net-pair capacitances in F, from the engine's CSV."""
    #- exact names, not a substring match: the FasterCap engine also
    #- drops Result_Matrix_Raw.csv and Result_Matrix_Avg.csv beside its
    #- netlist, and those are the solver's capacitance matrix, not the
    #- reduced net-to-net one this wants.
    name = (f"{cell}_k25d_pex_netlist.csv" if engine == "2.5D"
            else f"{cell}_FasterCap_Expanded_Netlist.csv")
    hit = os.path.join(out_dir, f"{cell}__{cell}", name)
    if not os.path.exists(hit):
        raise SystemExit(f"{engine} produced no {name}; see "
                         f"{os.path.join(WORK, cell)}-*.log")
    caps = {}
    with open(hit) as fi:
        for row in csv.reader(fi, delimiter=";"):
            if len(row) < 4 or not row[0].startswith("C"):
                continue
            try:
                val = float(row[3])
            except ValueError:
                continue
            key = tuple(sorted((row[1].strip(), row[2].strip())))
            caps[key] = caps.get(key, 0.0) + val * 1e-15
    return caps, hit


def write_subckt(path, cell, caps):
    """A port-bearing ngspice subcircuit; see point 3 in the docstring."""
    ab = caps.get(("A", "B"), 0.0)
    asub = caps.get(("A", "VSUBS"), 0.0)
    bsub = caps.get(("B", "VSUBS"), 0.0)
    with open(path, "w") as fo:
        fo.write(
            f"* {cell}: FasterCap extraction of the drawn MOM capacitor.\n"
            f"* Generated by mixed_signal/analog_layout/pex.py -- do not edit.\n"
            f"* a, b    the two plates\n"
            f"* vsubs   substrate; both plates see it, neither is shielded\n"
            f".subckt {cell.lower()} a b vsubs\n"
            f"Cab   a b     {ab:.6e}\n"
            f"Casub a vsubs {asub:.6e}\n"
            f"Cbsub b vsubs {bsub:.6e}\n"
            f".ends {cell.lower()}\n")
    return ab, asub, bsub


#- The settings to compare: kpex's own defaults, what this block uses,
#- and a mesh fine enough to stand in for the converged answer.
CONVERGE = (("default", "0.05", "50"),
            ("used", FC_TOLERANCE, FC_AMAX),
            ("fine", FC_TOLERANCE, "2"))


def converge(cell):
    """Show that FC_TOLERANCE / FC_AMAX are converged, on this geometry.

    A field solver's answer is only as good as its mesh, and a finger
    array is the geometry that punishes a coarse one: the capacitance
    lives on the facing edges, which is exactly where large panels blur
    it. Reporting Cab against the solver settings turns "the defaults are
    too loose" from a remembered fact into a measured one.
    """
    low = cell.lower()
    vals = {}
    for tag, tol, amax in CONVERGE:
        out_dir = os.path.join(WORK, f"{cell}-converge-{tag}")
        os.makedirs(out_dir, exist_ok=True)
        run_kpex(cell, "fastercap", out_dir, tolerance=tol, amax=amax)
        caps, _ = read_caps(out_dir, cell, "fastercap")
        vals[tag] = caps.get(("A", "B"), 0.0)
        print(f"{low}_fc_{tag} = {vals[tag]:.6e}")
    fine = vals["fine"]
    print(f"{low}_fc_converge = {abs(vals['used'] - fine) / fine:.6e}")
    print(f"{low}_fc_default_err = {abs(vals['default'] - fine) / fine:.6e}")


def control(cell, gds=None):
    """Did extraction notice that the two plates are one piece of metal?

    This is the check that turns out to matter. A bridged finger gap is
    DRC clean -- metal touching metal breaks no width, space or area
    rule -- and LVS against a device-free two-pin netlist calls it a
    match, because there is no device topology for the comparison to
    disagree about. Extraction is the step that sees it: the plates come
    back as one net, and the A-to-B capacitance the cell exists to
    provide is simply absent from the result.
    """
    low = cell.lower()
    out_dir = os.path.join(WORK, f"{cell}-control")
    os.makedirs(out_dir, exist_ok=True)
    run_kpex(cell, "fastercap", out_dir, gds=gds)
    caps, _ = read_caps(out_dir, cell, "fastercap")
    #- KLayout names a net that carries both labels "A,B"
    merged = any("," in n for pair in caps for n in pair)
    print(f"{low}_c_ab_fc = {caps.get(('A', 'B'), 0.0):.6e}")
    print(f"{low}_plates_merged = {1 if merged else 0}")


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("cells", nargs="+")
    ap.add_argument("--spice-dir", default=WORK)
    ap.add_argument("--gds", default=None,
                    help="layout path, for cells outside final_views")
    ap.add_argument("--control", action="store_true",
                    help="report whether the two plates came back as one "
                         "net, for the deliberately shorted control cell")
    ap.add_argument("--converge", action="store_true",
                    help="re-extract across mesh and tolerance settings "
                         "instead, to show the settings used are converged")
    a = ap.parse_args(argv)
    os.makedirs(WORK, exist_ok=True)
    os.makedirs(a.spice_dir, exist_ok=True)

    if a.converge:
        for cell in a.cells:
            converge(cell)
        return

    if a.control:
        for cell in a.cells:
            control(cell, gds=a.gds)
        return

    for cell in a.cells:
        low = cell.lower()
        out_dir = os.path.join(WORK, f"{cell}-pex")
        os.makedirs(out_dir, exist_ok=True)
        run_kpex(cell, "2.5D", out_dir, gds=a.gds)
        run_kpex(cell, "fastercap", out_dir, gds=a.gds)
        c25, _ = read_caps(out_dir, cell, "2.5D")
        cfc, csv_fc = read_caps(out_dir, cell, "fastercap")

        sub = os.path.join(a.spice_dir, f"{cell}_pex.spice")
        ab, asub, bsub = write_subckt(sub, cell, cfc)
        ab25 = c25.get(("A", "B"), 0.0)

        print(f"{low}_c_ab_fc = {ab:.6e}")
        print(f"{low}_c_ab_25d = {ab25:.6e}")
        print(f"{low}_c_asub_fc = {asub:.6e}")
        print(f"{low}_c_bsub_fc = {bsub:.6e}")
        #- the two engines are independent estimates of the same number;
        #- their spread is the honest uncertainty bar on it
        spread = abs(ab - ab25) / ab if ab else 1.0
        print(f"{low}_engine_spread = {spread:.6e}")
        #- what fraction of the plate-A charge goes to the substrate
        #- instead of to plate B
        print(f"{low}_bottom_frac = {asub / (ab + asub):.6e}")
        print(f"{low}_pex_netlist = 1")


if __name__ == "__main__":
    main(sys.argv[1:])
